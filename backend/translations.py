def custom_gettext(text, section='common'):
    """
    Возвращает перевод текста для текущего языка и раздела.
    Если перевода нет — возвращает оригинал (обычно русский).
    """
    from flask import g
    lang = g.get('current_lang', 'ru')          # по умолчанию русский
    section_dict = translations.get(lang, translations['ru']).get(section, {})
    return section_dict.get(text, text)