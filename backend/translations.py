def custom_gettext(text, section='common'):
    """
    Возвращает перевод текста для текущего языка и раздела.
    Если перевода нет — возвращает оригинал.
    """
    from flask import g
    lang = g.get('current_lang', 'ru')
    return translations.get(lang, translations['ru'])\
                      .get(section, {})\
                      .get(text, text)