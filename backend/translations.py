def custom_gettext(text):
    """
    Возвращает перевод текста для текущего языка.
    Если перевода нет — возвращает оригинал.
    """
    from flask import g
    lang = g.get('current_lang', 'ru')  # или session['lang'], см. ниже
    return translations.get(lang, translations['ru']).get(text, text)